"""exp-20260828-001 - phase-2 estimate-revision cash-conflict bar contract review.

Pre-registered by exp-20260811-001 ("if actual_cash_conflicts remains 0 while
settled counts scale past the bar, open ONE contract-review ticket for that
bar"). This runner verifies the amendment end to end without reading any
outcome/PnL value:

1. capability evidence recomputed from persisted quant_signals artifacts;
2. the regenerated readiness artifact keeps every pre-existing counter
   identical while adding the capability counters and flipping gate_ready
   under the amended rule;
3. the rebuilt reopen_readiness phase2 lane goes ready while every other
   lane's status is unchanged.

Usage: python quant/experiments/exp_20260828_001_estimate_revision_cash_conflict_bar_contract_review.py
"""

from __future__ import annotations

import json
import subprocess
import sys
from datetime import date
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "quant"))

from estimate_revision_outcomes import (  # noqa: E402
    _summarize_cash_admission_traces,
    persist_estimate_revision_readiness,
)

EXPERIMENT_ID = "exp-20260828-001"
ARTIFACT_DIR = REPO_ROOT / "data" / "experiments" / EXPERIMENT_ID
BEFORE_DIR = ARTIFACT_DIR / "before"
READINESS_PATH = REPO_ROOT / "data" / "non_ohlcv" / "estimate_revision_readiness_latest.json"
REOPEN_PATH = REPO_ROOT / "data" / "reopen_readiness.json"

# The daily artifact regenerated by this runner must keep the daily run's
# as_of clock (data calendar, not this process's wall clock).
FROZEN_AS_OF = "2026-08-27"

UNCHANGED_COUNTER_KEYS = (
    "independent_decisions",
    "mapped_ticker_count",
    "actual_cash_conflict_decisions",
    "settled_independent_decisions_by_horizon",
    "raw_rows",
    "usable_rows",
    "quarantined_decisions",
)


def main() -> int:
    checks: list[tuple[str, bool, str]] = []

    def check(name: str, passed: bool, detail: str) -> None:
        checks.append((name, bool(passed), detail))

    before = json.loads(
        (BEFORE_DIR / "estimate_revision_readiness_latest.json").read_text(
            encoding="utf-8"
        )
    )
    before_reopen = json.loads(
        (BEFORE_DIR / "reopen_readiness.json").read_text(encoding="utf-8")
    )

    # 1. Capability evidence (counts only; no outcome fields exist in traces).
    trace = _summarize_cash_admission_traces(REPO_ROOT / "data", date(2026, 8, 28))
    check(
        "trace_capability_evidence",
        trace["trace_ok_sessions"] >= 30
        and trace["lifetime_structured_conflicts"] >= 1,
        f"trace_ok_sessions={trace['trace_ok_sessions']} "
        f"lifetime_structured_conflicts={trace['lifetime_structured_conflicts']}",
    )

    # 2. Regenerate the readiness artifact under the amended contract.
    after = persist_estimate_revision_readiness(
        as_of=FROZEN_AS_OF,
        data_dir=REPO_ROOT / "data",
        output_dir=REPO_ROOT / "data" / "non_ohlcv",
    )
    check(
        "before_gate_closed_after_gate_open",
        before.get("gate_ready") is False and after.get("gate_ready") is True,
        f"before={before.get('gate_ready')} after={after.get('gate_ready')}",
    )
    unchanged = {
        key: (before.get(key), after.get(key)) for key in UNCHANGED_COUNTER_KEYS
    }
    check(
        "pre_existing_counters_unchanged",
        all(pair[0] == pair[1] for pair in unchanged.values()),
        json.dumps({k: v for k, v in unchanged.items() if v[0] != v[1]}),
    )
    check(
        "capability_counters_present",
        after.get("cash_admission_trace_ok_sessions") == trace["trace_ok_sessions"]
        and after.get("structured_cash_conflict_observations_lifetime")
        == trace["lifetime_structured_conflicts"],
        json.dumps(
            {
                "cash_admission_trace_ok_sessions": after.get(
                    "cash_admission_trace_ok_sessions"
                ),
                "structured_cash_conflict_observations_lifetime": after.get(
                    "structured_cash_conflict_observations_lifetime"
                ),
            }
        ),
    )
    payload_text = json.dumps(after)
    check(
        "no_outcome_fields_in_readiness_payload",
        all(
            token not in payload_text
            for token in ("pnl", "return_pct", "replacement_value", "sharpe")
        ),
        "readiness payload carries counts/hashes only",
    )

    # 3. Rebuild the downstream reopen surface and compare lane statuses.
    subprocess.run(
        [sys.executable, str(REPO_ROOT / "scripts" / "build_reopen_readiness.py")],
        check=True,
        capture_output=True,
    )
    after_reopen = json.loads(REOPEN_PATH.read_text(encoding="utf-8"))

    def lane_statuses(doc):
        return {lane.get("lane"): lane.get("status") for lane in doc.get("lanes", [])}

    before_statuses = lane_statuses(before_reopen)
    after_statuses = lane_statuses(after_reopen)
    check(
        "phase2_lane_flips_ready",
        before_statuses.get("phase2_estimate_revision") == "not_ready"
        and after_statuses.get("phase2_estimate_revision") == "ready",
        f"before={before_statuses.get('phase2_estimate_revision')} "
        f"after={after_statuses.get('phase2_estimate_revision')}",
    )
    other_changed = {
        lane: (before_statuses.get(lane), after_statuses.get(lane))
        for lane in after_statuses
        if lane != "phase2_estimate_revision"
        and before_statuses.get(lane) != after_statuses.get(lane)
    }
    check(
        "other_lane_statuses_unchanged",
        not other_changed,
        json.dumps(other_changed),
    )

    result = {
        "experiment_id": EXPERIMENT_ID,
        "frozen_as_of": FROZEN_AS_OF,
        "trace_capability_evidence": trace,
        "checks": [
            {"name": name, "passed": passed, "detail": detail}
            for name, passed, detail in checks
        ],
        "all_passed": all(passed for _, passed, _ in checks),
        "trade_enabled": False,
        "production_impact": {
            "alters_signal_generation": False,
            "alters_candidate_ranking": False,
            "alters_sizing": False,
            "alters_orders": False,
            "scope": "phase2_reopen_gate_contract_amendment_only",
        },
    }
    ARTIFACT_DIR.mkdir(parents=True, exist_ok=True)
    out_path = ARTIFACT_DIR / "contract_review_verification.json"
    out_path.write_text(
        json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    for name, passed, detail in checks:
        print(f"[{'PASS' if passed else 'FAIL'}] {name}: {detail}")
    print(f"verification -> {out_path}")
    return 0 if result["all_passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
